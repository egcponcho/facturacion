    reglas = sa.table("reglas_clasificacion", *[sa.column(c) for c in (
        "codigo", "tipo_ambito", "codigo_ambito", "pais", "tipo_regla", "prioridad", "tipo_fuente", "familia",
        "activo", "requiere_revision", "inciso_id", "actualizado_en")])
    conds = sa.table("reglas_condiciones", sa.column("regla_id"), sa.column("grupo"), sa.column("campo"), sa.column("operador"),
                     sa.column("valor", sa.JSON), sa.column("negado", sa.Boolean))
    for iid, pais, sub6, cond, prio, fuente in filas:
        cond = json.loads(cond) if isinstance(cond, str) else (cond or {})
        lista = _condiciones(cond or {})
        if not lista and not prio:
            continue
