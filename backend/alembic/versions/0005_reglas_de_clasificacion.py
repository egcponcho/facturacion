def _condiciones(cond: dict) -> list[tuple]:
    out = []
    for k, v in cond.items():
        if v in (None, "", []):
            continue
        if k in ("cifMax", "cifMin"):
            out.append(("valorCIF", "LTE" if k == "cifMax" else "GT", v))
        else:
            out.append((k, "IN" if isinstance(v, list) else "EQUAL", v))
    return out


def _leer_condiciones() -> list:
    return op.get_bind().execute(sa.text("SELECT id, pais, sub6, cond, prio, fuente FROM incisos_nacionales")).fetchall()


