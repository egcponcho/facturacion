        con.execute(reglas.insert().values(
            codigo=codigo, tipo_ambito="NATIONAL_CODE", codigo_ambito=sub6 or "", pais=pais,
            tipo_regla="NATIONAL_SELECT", prioridad=int(prio or 0), tipo_fuente=FUENTE.get(fuente or "", "MANUAL"),
            familia="NATIONAL_CODE", activo=True, requiere_revision=False, inciso_id=iid, actualizado_en=datetime.now()))
        rid = con.execute(sa.text("SELECT id FROM reglas_clasificacion WHERE codigo = :c"), {"c": codigo}).scalar_one()
        for campo, operador, valor in lista:
            con.execute(conds.insert().values(regla_id=rid, grupo=1, campo=campo, operador=operador, valor=valor, negado=False))

